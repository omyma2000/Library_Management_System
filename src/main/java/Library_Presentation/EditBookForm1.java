    private void jButton_EditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_EditActionPerformed
                                         

    System.out.println("EDIT BUTTON CLICKED");

    Library_Domain.Book book = new Library_Domain.Book();

    int id = Integer.parseInt(jTextField_ID.getText());
    String isbn = jTextField_ISBN.getText();

    System.out.println("verif = " + verif());

    // 🔴 تحقق من الحقول
    if(!verif())
    {
        JOptionPane.showMessageDialog(null,
            "ISBN, Name, Author and Genre are Empty",
            "Empty Data",
            0);
        return;
    }

    try {

        System.out.println("ID = " + id);
        System.out.println("imagePath = " + imagePath);

        // 🔴 ISBN check الصحيح (يستثني نفس الكتاب)
        if(book.isISBNexists(isbn) && book.isbnExistsForOtherBook(isbn, id))
        {
            JOptionPane.showMessageDialog(null,
                "The ISBN already exists",
                "Wrong ISBN",
                0);
            return;
        }

        String name = jTextField_Name.getText();
        String publisher = jTextField_Publisher.getText();
        String description = jTextArea1_Description.getText();

        Integer author_id = Integer.parseInt(jLabel1_Author_ID.getText());
        Integer genre_id = Integer.parseInt(jLabel1_Genre_ID.getText());
        Integer quantity = Integer.parseInt(jSpinner_Quantity.getValue().toString());
        double price = Double.parseDouble(jTextField_Price_.getText());

        SimpleDateFormat dateFormat = new SimpleDateFormat("yyyy-MM-dd");
        String date_revived = dateFormat.format(jCalendarComboBox_Date.getDate());

        byte[] img = null;

        if(imagePath != null && !imagePath.trim().isEmpty())
        {
            Path path = Paths.get(imagePath);
            img = Files.readAllBytes(path);
        }

        book.editBook(id, name, author_id, genre_id, quantity,
                publisher, date_revived, price, description, img);

    }
    catch(IOException ex)
    {
        JOptionPane.showMessageDialog(null,
            "Make sure add cover Image : " + ex.getMessage());
    }
    catch(NumberFormatException ex)
    {
        JOptionPane.showMessageDialog(null,
            "You entered wrong data field : " + ex.getMessage());
    }
    catch(NullPointerException ex)
    {
        JOptionPane.showMessageDialog(null,
            "You need to select Date  : " + ex.getMessage());
    }

    }//GEN-LAST:event_jButton_EditActionPerformed

