    private void jButton_Search_ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_Search_ActionPerformed
    String idText = jTextField_ID.getText().trim();
    String isbn = jTextField_ISBN.getText().trim();

    Library_Domain.Book selectedBook = null;

    if(!idText.isEmpty())
    {
        selectedBook = book.searchBookByID(Integer.parseInt(idText));
    }
    else if(!isbn.isEmpty())
    {
        selectedBook = book.searchBookByISBN(isbn);
    }
    else
    {
        JOptionPane.showMessageDialog(
                null,
                "Enter Book ID or ISBN",
                "Search",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    if(selectedBook != null)
    {
        jTextField_ID.setText(String.valueOf(selectedBook.getId()));
        jTextField_ISBN.setText(selectedBook.getIsbn());
        jTextField_Name.setText(selectedBook.getName());
        jTextField_Publisher.setText(selectedBook.getPublisher());
        jTextField_Price_.setText(String.valueOf(selectedBook.getPrice()));
        jSpinner_Quantity.setValue(selectedBook.getQuantity());
        jTextArea1_Description.setText(selectedBook.getDescription());
        java.util.Date date = null;
         try {
        date = new SimpleDateFormat("yyyy-MM-dd").parse(selectedBook.getDate_revived());
        } catch (Exception e) {
             e.printStackTrace();
                     }

         jCalendarComboBox_Date.setDate(date);
        jLabel1_Author_ID.setText(String.valueOf(selectedBook.getAuthor_id()));
        // author name
        String fullName = (authors.getAuthorsByID(selectedBook.getAuthor_id())).getFirstName()+" "+
         (authors.getAuthorsByID(selectedBook.getAuthor_id())).getLastName();
        jTextField_Author.setText(fullName);
        jLabel1_Genre_ID.setText(String.valueOf(selectedBook.getGenre_id()));
         for(Map.Entry<String,Integer> entry : genreMap.entrySet()){
              if(Objects.equals(selectedBook.getGenre_id(), entry.getValue())){
                 jComboBox_Genre.setSelectedItem(entry.getKey());
                    break;
                         }
                     }
          byte[] image = selectedBook.getCover();
                if (image != null && image.length > 0) {
                    func.displayImage(140, 145, image, "", jLabel_image_);
                } else {
                    jLabel_image_.setIcon(null);
                }
    }
    else
    {
        JOptionPane.showMessageDialog(
                null,
                "Book Not Found",
                "Search",
                JOptionPane.INFORMATION_MESSAGE
        );

        jTextField_Name.setText("");
        jTextField_Publisher.setText("");
        jTextField_Price_.setText("");
    }

        
        
    }//GEN-LAST:event_jButton_Search_ActionPerformed
