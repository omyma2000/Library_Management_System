    private void jSpinner_BookIDStateChanged(javax.swing.event.ChangeEvent evt) {//GEN-FIRST:event_jSpinner_BookIDStateChanged
        // TODO add your handling code here:                                       
    int _book_id = (int) jSpinner_BookID.getValue();
    
    // أولاً نتحقق لو الرقم صفر أو سالب عشان ما يضربش خطأ في الداتابيز
    if (_book_id <= 0) {
        jLabelAlvilable.setText("No");
        jLabelAlvilable.setForeground(java.awt.Color.RED);
        return; // يوقف هنا
    }
    
    // استدعاء دالة الفحص بعد التعديلات الأخيرة التي أجريناها
    if (issue_Book.checkBookAvailability(_book_id))
            {
        jLabelAlvilable.setText("Yes");
        jLabelAlvilable.setForeground(java.awt.Color.GREEN); // اللون أخضر
    } else {
        jLabelAlvilable.setText("No");
        jLabelAlvilable.setForeground(java.awt.Color.RED); // اللون أحمر
        JOptionPane.showMessageDialog(null, "this book not available or out of stock","Unavailable",JOptionPane.WARNING_MESSAGE);
        return;
    }
    }//GEN-LAST:event_jSpinner_BookIDStateChanged
