    private void jButton_Issue_ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_Issue_ActionPerformed
                                                
    int _book_id = (int) jSpinner_BookID.getValue();
    int _member_id = (int) jSpinner_MemberID.getValue();
    String _note = jTextArea_note.getText();
    SimpleDateFormat dateFormat = new SimpleDateFormat("yyyy-MM-dd");
    
    // 1. التحقق المبدئي من أن الأرقام ليست أصفاراً أو سالبة
    if (_book_id <= 0 || _member_id <= 0) {
        JOptionPane.showMessageDialog(null, "Enter correct Book ID and Member ID!", "wrong", JOptionPane.ERROR_MESSAGE);
        return; 
    }
    
    // 2. التحقق من وجود العضو فعلياً في قاعدة البيانات
    if (!issue_Book.checkMemberExists(_member_id)) {
        JOptionPane.showMessageDialog(null, "This Member ID does not exist in the database!", "Member Not Found", JOptionPane.ERROR_MESSAGE);
        return; // يوقف التنفيذ تماماً ولا يكمل
    }
    
    // 3. الفحص الصارم لإتاحة الكتاب (تأكدي من مطابقة اسم الدالة المصلحة في الكلاس)
    if (issue_Book.checkBookAvailability(_book_id)) {
        jLabelAlvilable.setText("Yes");
        jLabelAlvilable.setForeground(java.awt.Color.GREEN);
    } else {
        jLabelAlvilable.setText("No"); 
        jLabelAlvilable.setForeground(java.awt.Color.RED);
        JOptionPane.showMessageDialog(null, "This book is not available or out of stock!", "Unavailable", JOptionPane.WARNING_MESSAGE);
        return; // يوقف التنفيذ هنا تماماً ولا يسمح بالتسجيل
    }
    
    // 4. التحقق من وجود التواريخ
    if (jCalendarComboBox_issueDate.getDate() == null || jCalendarComboBox_returnDate.getDate() == null) {
        JOptionPane.showMessageDialog(null, "Select the issue date and return date please!", "wrong", JOptionPane.ERROR_MESSAGE);
        return;
    }
    
    try {
        String _issue_date = dateFormat.format(jCalendarComboBox_issueDate.getDate());
        String _return_date = dateFormat.format(jCalendarComboBox_returnDate.getDate());
        
        java.util.Date parsedIssue = dateFormat.parse(_issue_date);
        java.util.Date parsedReturn = dateFormat.parse(_return_date);
        
        // 5. التحقق المنطقي من التواريخ (أن تاريخ الإرجاع بعد الإعارة)
        if (parsedReturn.before(parsedIssue) || parsedReturn.equals(parsedIssue)) {
            JOptionPane.showMessageDialog(null, "The return date must be after the issued date!", "wrong!", JOptionPane.WARNING_MESSAGE);
            return; 
        }
        
        // الإضافة الفعلية بعد تخطي كل شروط الحماية بنجاح
        issue_Book.addIssue(_book_id, _member_id, "issued", _issue_date, _return_date, _note);
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Not issue: " + e.getMessage(), "wrong", JOptionPane.ERROR_MESSAGE);
    }


    }//GEN-LAST:event_jButton_Issue_ActionPerformed

